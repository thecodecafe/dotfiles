#!/bin/sh

set -eu

usage() {
    printf 'Usage: %s <link|unlink> <skills-directory> <generated-directory> <commands-directory>\n' "$0" >&2
    exit 64
}

[ "$#" -eq 4 ] || usage
operation=$1
skills_input=$2
cache_input=$3
commands_input=$4
project_root=$(CDPATH= cd -- "$(dirname "$0")/.." && pwd -P)

case "$operation" in
    link|unlink) ;;
    *) usage ;;
esac

# Resolve missing directories too, so unlink can remove broken owned links.
resolve_directory() {
    if [ -d "$1" ]; then
        (CDPATH= cd -- "$1" && pwd -P)
        return
    fi
    resolved_parent=$(resolve_directory "$(dirname "$1")")
    directory_name=$(basename "$1")
    case "$directory_name" in
        .) printf '%s\n' "$resolved_parent" ;;
        ..) dirname "$resolved_parent" ;;
        *) printf '%s/%s\n' "${resolved_parent%/}" "$directory_name" ;;
    esac
}

skills_dir=$(resolve_directory "$skills_input")
cache_dir=$(resolve_directory "$cache_input")
commands_dir=$(resolve_directory "$commands_input")

case "$cache_dir" in
    /|"$project_root"|"${HOME:-}"|"$skills_dir"|"$commands_dir")
        printf 'Refusing unsafe generated directory: %s\n' "$cache_dir" >&2
        exit 1
        ;;
esac
[ "$commands_dir" != / ] || { printf '%s\n' 'Refusing / as the commands directory.' >&2; exit 1; }

valid_name() {
    [ "${#1}" -le 64 ] && printf '%s\n' "$1" | LC_ALL=C grep -Eq '^[a-z0-9]+(-[a-z0-9]+)*$'
}

is_generated() {
    [ ! -L "$1" ] && [ -f "$1" ] \
        && head -n 2 "$1" | tail -n 1 | grep -Fqx '# Generated by dotfiles/manage-opencode-commands.sh; do not edit.'
}

unlink_owned_command() {
    installed_command=$commands_dir/$1.md
    generated_command=$cache_dir/$1.md
    if [ -e "$generated_command" ] || [ -L "$generated_command" ]; then
        is_generated "$generated_command" || return 0
    fi
    if [ -L "$installed_command" ] && [ "$(readlink "$installed_command")" = "$generated_command" ]; then
        rm "$installed_command"
        printf 'Unlinked command: %s\n' "$installed_command"
    fi
}

if [ "$operation" = unlink ]; then
    for installed_command in "$commands_dir"/*.md; do
        [ -L "$installed_command" ] || continue
        command_name=${installed_command##*/}
        command_name=${command_name%.md}
        valid_name "$command_name" || continue
        unlink_owned_command "$command_name"
    done
    exit 0
fi

[ -d "$skills_dir" ] || { printf 'Source skills directory does not exist: %s\n' "$skills_dir" >&2; exit 1; }

# Validate names before generating anything; skill bodies remain untouched.
for skill_dir in "$skills_dir"/*; do
    [ -d "$skill_dir" ] && [ -f "$skill_dir/SKILL.md" ] || continue
    skill_name=${skill_dir##*/}
    if ! valid_name "$skill_name"; then
        printf 'Invalid skill directory name: %s\n' "$skill_name" >&2
        exit 1
    fi
done

mkdir -p "$cache_dir" "$commands_dir"

# Prune only owned adapters whose skills no longer exist, including broken links.
for installed_command in "$commands_dir"/*.md; do
    [ -L "$installed_command" ] || continue
    command_name=${installed_command##*/}
    command_name=${command_name%.md}
    valid_name "$command_name" || continue
    [ -f "$skills_dir/$command_name/SKILL.md" ] || unlink_owned_command "$command_name"
done
for generated_command in "$cache_dir"/*.md; do
    is_generated "$generated_command" || continue
    command_name=${generated_command##*/}
    command_name=${command_name%.md}
    valid_name "$command_name" || continue
    if [ ! -f "$skills_dir/$command_name/SKILL.md" ]; then
        rm "$generated_command"
        printf 'Removed stale generated adapter: %s\n' "$generated_command"
    fi
done

temporary_file=
cleanup() {
    if [ -n "$temporary_file" ]; then
        rm -f "$temporary_file"
    fi
}
trap cleanup EXIT
trap 'exit 1' HUP INT TERM
link_failed=0

for skill_dir in "$skills_dir"/*; do
    [ -d "$skill_dir" ] && [ -f "$skill_dir/SKILL.md" ] || continue
    skill_name=${skill_dir##*/}
    generated_command=$cache_dir/$skill_name.md
    if [ -e "$generated_command" ] || [ -L "$generated_command" ]; then
        if ! is_generated "$generated_command"; then
            printf 'Refusing to replace unrelated generated-path entry: %s\n' "$generated_command" >&2
            link_failed=1
            continue
        fi
    fi

    temporary_file=$(mktemp "$cache_dir/.adapter.XXXXXX")
    printf '%s\n' \
        '---' \
        '# Generated by dotfiles/manage-opencode-commands.sh; do not edit.' \
        "description: Run the shared $skill_name skill" \
        '---' \
        '' \
        "Load the \"$skill_name\" skill using the native skill tool, then follow its workflow without displaying this handoff." \
        "Use the following text as the user's input for that skill:" \
        '$ARGUMENTS' > "$temporary_file"

    if [ -f "$generated_command" ] && cmp -s "$temporary_file" "$generated_command"; then
        rm "$temporary_file"
    else
        mv "$temporary_file" "$generated_command"
    fi
    temporary_file=

    if ! "$project_root/scripts/manage-dotfile-link.sh" link "$generated_command" "$commands_dir/$skill_name.md"; then
        link_failed=1
    fi
done

exit "$link_failed"
